package com.intellij.aspect.tools.ccdb;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParseException;
import com.google.gson.Strictness;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;

/** Generates one .clangd beside sibling target directories containing compilation databases. */
public final class ClangdGenerator {
  private static final Gson JSON =
      new GsonBuilder().setStrictness(Strictness.STRICT).disableHtmlEscaping().create();
  private static final String HEADER =
      "# Generated by ccdb; manual edits will be overwritten.\n";
  private static final String USAGE =
      "Usage: ccdb <path/to/target/compile_commands.json>... [@response-file ...]";

  private ClangdGenerator() {}

  public static void main(String[] args) {
    if (args.length == 1 && (args[0].equals("--help") || args[0].equals("-h"))) {
      System.out.println(USAGE);
      return;
    }
    // bazel run executes in its runfiles tree. Honor the user's original directory.
    String invocationDirectory = System.getenv("BUILD_WORKING_DIRECTORY");
    Path base = Path.of(invocationDirectory == null ? "" : invocationDirectory).toAbsolutePath();
    try {
      List<Path> outputs;
      if (args.length > 0 && args[0].equals("--bazel-runfiles")) {
        outputs = BazelConfigGenerator.generate(List.of(args).subList(1, args.length));
      } else {
        outputs = generate(List.of(args), base);
      }
      for (Path output : outputs) {
        System.out.println("Generated " + output);
      }
    } catch (IOException | IllegalArgumentException | JsonParseException error) {
      System.err.println("ccdb: " + error.getMessage());
      System.err.println(USAGE);
      System.exit(1);
    }
  }

  static List<Path> generate(List<String> arguments, Path base) throws IOException {
    Set<Path> databases = new TreeSet<>(ResponseFiles.expand(arguments, base));
    if (databases.isEmpty()) {
      throw new IllegalArgumentException("Provide at least one compilation database");
    }
    Map<Path, Map<Path, Set<String>>> folders = new TreeMap<>();
    Map<Path, Path> owners = new TreeMap<>();
    for (Path database : databases) {
      if (database.getFileName() == null
          || !database.getFileName().toString().equals("compile_commands.json")) {
        throw new IllegalArgumentException("Expected compile_commands.json: " + database);
      }
      Path target = database.getParent();
      Path folder = target.getParent();
      if (folder == null) {
        throw new IllegalArgumentException("Database needs a target parent directory: " + database);
      }
      Set<String> sources = readSources(database, folder, owners);
      folders.computeIfAbsent(folder, unused -> new TreeMap<>()).put(target, sources);
    }

    // Parse and validate every database before changing any configuration file.
    Map<Path, String> outputs = new TreeMap<>();
    for (var entry : folders.entrySet()) {
      outputs.put(entry.getKey().resolve(".clangd"), render(entry.getKey(), entry.getValue()));
    }
    for (var output : outputs.entrySet()) {
      Files.writeString(output.getKey(), output.getValue());
    }
    return List.copyOf(outputs.keySet());
  }

  static JsonArray readDatabase(Path database) throws IOException {
    JsonElement root;
    try (var reader = Files.newBufferedReader(database)) {
      root = JSON.fromJson(reader, JsonElement.class);
    } catch (JsonParseException error) {
      throw new IllegalArgumentException("Invalid JSON in " + database + ": " + error.getMessage());
    }
    if (root == null || !root.isJsonArray()) {
      throw new IllegalArgumentException("Expected a JSON array in " + database);
    }
    return root.getAsJsonArray();
  }

  private static Set<String> readSources(
      Path database, Path folder, Map<Path, Path> owners) throws IOException {
    return readSources(readDatabase(database), database, folder, owners);
  }

  static Set<String> readSources(
      JsonArray commands, Path database, Path folder, Map<Path, Path> owners) {
    Set<String> sources = new TreeSet<>();
    int index = 0;
    for (JsonElement element : commands) {
      String context = database + " entry " + index++;
      if (!element.isJsonObject()) {
        throw new IllegalArgumentException("Expected an object in " + context);
      }
      JsonObject command = element.getAsJsonObject();
      Path directory = database.getParent().resolve(stringField(command, "directory", context));
      // Do not call toRealPath(): symlink paths must stay in the mirrored tree.
      Path source = directory.resolve(stringField(command, "file", context)).normalize();
      if (!source.startsWith(folder) || source.equals(folder)) {
        throw new IllegalArgumentException(
            "Source " + source + " is outside configuration folder " + folder + " (" + context + ")");
      }
      Path previous = owners.putIfAbsent(source, database);
      if (previous != null && !previous.equals(database)) {
        throw new IllegalArgumentException(
            "Source " + source + " belongs to multiple databases: " + previous + " and " + database);
      }
      sources.add(unixPath(folder.relativize(source)));
    }
    return sources;
  }

  static String stringField(JsonObject object, String field, String context) {
    JsonElement value = object.get(field);
    if (value == null || !value.isJsonPrimitive() || !value.getAsJsonPrimitive().isString()
        || value.getAsString().isEmpty()) {
      throw new IllegalArgumentException("Expected nonempty string '" + field + "' in " + context);
    }
    return value.getAsString();
  }

  static String render(Path folder, Map<Path, Set<String>> targets) {
    StringBuilder yaml = new StringBuilder(HEADER);
    boolean first = true;
    for (var target : targets.entrySet()) {
      if (target.getValue().isEmpty()) {
        continue;
      }
      if (!first) {
        yaml.append("---\n");
      }
      first = false;
      yaml.append("If:\n  PathMatch:\n");
      for (String source : target.getValue()) {
        yaml.append("    - ").append(JSON.toJson(regexLiteral(source))).append('\n');
      }
      yaml.append("CompileFlags:\n  CompilationDatabase: ")
          .append(JSON.toJson(unixPath(folder.relativize(target.getKey())))).append('\n');
    }
    return yaml.toString();
  }

  private static String regexLiteral(String path) {
    StringBuilder result = new StringBuilder();
    for (char c : path.toCharArray()) {
      // Escape regex metacharacters individually; clangd does not support Java's \Q...\E.
      if ("\\.^$|?*+()[]{}".indexOf(c) >= 0) {
        result.append('\\');
      }
      result.append(c);
    }
    return result.toString();
  }

  private static String unixPath(Path path) {
    return path.toString().replace(path.getFileSystem().getSeparator(), "/");
  }
}
