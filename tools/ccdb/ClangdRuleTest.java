package com.intellij.aspect.tools.ccdb;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonParser;
import com.intellij.aspect.tools.RunfilesRepo;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;
import org.junit.Test;

public class ClangdRuleTest {
  private JsonArray commands(String property, String folder) throws Exception {
    String[] outputs = System.getProperty(property).split(" ");
    assertEquals(Set.of(folder + "/.clangd", folder + "/clangd/compile_commands.json"),
        new HashSet<>(Arrays.asList(outputs)));
    Path config = RunfilesRepo.location(folder + "/.clangd");
    String yaml = Files.readString(config);
    assertEquals("# Generated by ccdb_clangd; manual edits will be overwritten.\n"
        + "CompileFlags:\n  CompilationDatabase: \"clangd\"\n", yaml);
    String database = Files.readString(config.getParent().resolve("clangd/compile_commands.json"));
    assertFalse(database.contains("{EXECROOT}"));
    assertFalse(database.contains("__BAZEL_XCODE_"));
    assertFalse(database.contains("__BAZEL_EXECUTION_ROOT"));
    JsonArray commands = JsonParser.parseString(database).getAsJsonArray();
    for (var entry : commands) {
      String directory = entry.getAsJsonObject().get("directory").getAsString();
      assertTrue(Path.of(directory).isAbsolute());
      assertFalse(directory.contains("sandbox"));
    }
    return commands;
  }

  @Test public void buildsConfigAndResolvedTransitiveDatabase() throws Exception {
    JsonArray commands = commands("ccdb.configs", "tools/ccdb/testdata");
    assertEquals(3, commands.size());
    Set<String> sources = new HashSet<>();
    for (var entry : commands) {
      sources.add(entry.getAsJsonObject().get("file").getAsString());
    }
    assertEquals(Set.of("tools/ccdb/testdata/alpha.cc", "tools/ccdb/testdata/beta.cc",
        "tools/ccdb/testdata/sub/library.cc"), sources);
  }

  @Test public void subpackageCanIncludeItsPrivateTargets() throws Exception {
    JsonArray commands = commands("ccdb.private_configs", "tools/ccdb/testdata/sub");
    assertEquals(1, commands.size());
    assertTrue(commands.get(0).getAsJsonObject().getAsJsonArray("arguments")
        .toString().contains("-DPRIVATE_LIBRARY"));
  }

  @Test public void headersOnlyPackageStillBuildsConfigAndEmptyDatabase() throws Exception {
    assertTrue(commands("ccdb.empty_configs", "tools/ccdb/testdata/empty").isEmpty());
  }
}
