package com.intellij.aspect.tools.ccdb;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertThrows;
import static org.junit.Assert.assertTrue;

import com.google.gson.Gson;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

public class ClangdGeneratorTest {
  @Rule public TemporaryFolder temporary = new TemporaryFolder();

  private Path root() {
    return temporary.getRoot().toPath();
  }

  private Path database(String path, String directory, String... files) throws IOException {
    Path database = root().resolve(path);
    Files.createDirectories(database.getParent());
    Files.writeString(database, new Gson().toJson(
        java.util.Arrays.stream(files)
            .map(file -> Map.of("directory", directory, "file", file, "command", "c++ -c " + file))
            .toList()));
    return database;
  }

  @Test public void groupsSiblingTargetsWithoutAnAggregateRootConfig() throws Exception {
    Path a = database("compdb/src/targetA/compile_commands.json", "..", "foo.cpp", "bar.cpp");
    Path b = database("compdb/src/targetB/compile_commands.json", "..", "baz.cpp");
    Path c = database("compdb/extra/targetC/compile_commands.json", "..", "other.cpp");
    String originalDatabase = Files.readString(a);
    List<String> inputs = List.of(b.toString(), c.toString(), a.toString(), a.toString());

    List<Path> outputs = ClangdGenerator.generate(inputs, root());

    assertEquals(List.of(root().resolve("compdb/extra/.clangd"), root().resolve("compdb/src/.clangd")), outputs);
    assertFalse(Files.exists(root().resolve("compdb/.clangd")));
    assertFalse(Files.exists(a.getParent().resolve(".clangd")));
    String yaml = Files.readString(root().resolve("compdb/src/.clangd"));
    assertEquals("""
        # Generated by ccdb; manual edits will be overwritten.
        If:
          PathMatch:
            - "bar\\\\.cpp"
            - "foo\\\\.cpp"
        CompileFlags:
          CompilationDatabase: "targetA"
        ---
        If:
          PathMatch:
            - "baz\\\\.cpp"
        CompileFlags:
          CompilationDatabase: "targetB"
        """, yaml);
    ClangdGenerator.generate(List.of(a.toString(), c.toString(), b.toString()), root());
    assertEquals(yaml, Files.readString(root().resolve("compdb/src/.clangd")));
    assertEquals(originalDatabase, Files.readString(a));
  }

  @Test public void resolvesAbsoluteAndRelativeFilesAndDeduplicatesCommands() throws Exception {
    Path folder = root().resolve("compdb/src");
    Path a = database("compdb/src/targetA/compile_commands.json", folder.toString(),
        "nested/foo.cpp", folder.resolve("nested/foo.cpp").toString(), "./bar.cpp");
    ClangdGenerator.generate(List.of(a.toString()), root());
    String yaml = Files.readString(folder.resolve(".clangd"));
    assertTrue(yaml.contains("    - \"nested/foo\\\\.cpp\"\n"));
    assertEquals(2, yaml.lines().filter(line -> line.startsWith("    - ")).count());
    assertFalse(yaml.contains(folder.toString()));
  }

  @Test public void preservesSymlinkPathsAndEscapesRegexAndYaml() throws Exception {
    Path realSource = root().resolve("real.cpp");
    Files.writeString(realSource, "int main() {}\n");
    String filename = "a [1]+(x)$'\".cpp";
    Path database = database("compdb/src/target A/compile_commands.json", "..", filename);
    Files.createSymbolicLink(database.getParent().getParent().resolve(filename), realSource);

    ClangdGenerator.generate(List.of(database.toString()), root());

    String yaml = Files.readString(root().resolve("compdb/src/.clangd"));
    String encoded = yaml.lines().filter(line -> line.startsWith("    - ")).findFirst().orElseThrow().substring(6);
    String pattern = new Gson().fromJson(encoded, String.class);
    assertTrue(filename.matches(pattern));
    assertFalse("a 1xxx.cpp".matches(pattern));
    assertFalse(pattern.contains("real"));
    assertTrue(yaml.contains("CompilationDatabase: \"target A\""));
  }

  @Test public void supportsMixedArgumentsAndNestedQuotedResponseFiles() throws Exception {
    Path a = database("compdb/source dir/targetA/compile_commands.json", "..", "foo.cpp");
    Path b = database("compdb/source dir/targetB/compile_commands.json", "..", "bar.cpp");
    Path responses = root().resolve("responses");
    Files.createDirectories(responses.resolve("nested"));
    Files.writeString(responses.resolve("nested/more.rsp"),
        "'../../compdb/source dir/targetB/compile_commands.json'\n");
    Files.writeString(responses.resolve("inputs.rsp"),
        "# databases relative to this response file\n"
        + "\"../compdb/source dir/targetA/compile_commands.json\" @nested/more.rsp\n");

    List<Path> outputs = ClangdGenerator.generate(
        List.of("@responses/inputs.rsp", a.toString(), b.toString()), root());

    assertEquals(List.of(root().resolve("compdb/source dir/.clangd")), outputs);
    assertEquals(2, Files.readString(outputs.getFirst()).lines()
        .filter(line -> line.startsWith("  CompilationDatabase:")).count());
  }

  @Test public void rejectsResponseCyclesAndUnclosedQuotes() throws Exception {
    Files.writeString(root().resolve("a.rsp"), "@b.rsp\n");
    Files.writeString(root().resolve("b.rsp"), "@a.rsp\n");
    assertTrue(assertThrows(IllegalArgumentException.class,
        () -> ClangdGenerator.generate(List.of("@a.rsp"), root())).getMessage().contains("cycle"));
    Files.writeString(root().resolve("bad.rsp"), "\"unfinished\n");
    assertTrue(assertThrows(IllegalArgumentException.class,
        () -> ClangdGenerator.generate(List.of("@bad.rsp"), root())).getMessage().contains("Unclosed quote"));
  }

  @Test public void validatesAllDatabasesBeforeOverwritingAnything() throws Exception {
    Path a = database("compdb/src/targetA/compile_commands.json", "..", "foo.cpp");
    Path b = database("compdb/src/targetB/compile_commands.json", "..", "bar.cpp");
    Path config = root().resolve("compdb/src/.clangd");
    Files.writeString(config, "existing configuration\n");
    for (String invalid : List.of("{", "{}", "[{}]", "[{\"directory\":1,\"file\":\"x.cpp\"}]", "[] trailing")) {
      Files.writeString(b, invalid);
      assertThrows(IllegalArgumentException.class,
          () -> ClangdGenerator.generate(List.of(a.toString(), b.toString()), root()));
      assertEquals("existing configuration\n", Files.readString(config));
    }
  }

  @Test public void rejectsAmbiguousSourcesAndPathsOutsideConfigFolder() throws Exception {
    Path a = database("compdb/src/targetA/compile_commands.json", "..", "foo.cpp");
    Path b = database("compdb/src/targetB/compile_commands.json", "..", "foo.cpp");
    assertTrue(assertThrows(IllegalArgumentException.class,
        () -> ClangdGenerator.generate(List.of(a.toString(), b.toString()), root()))
        .getMessage().contains("multiple databases"));
    database("compdb/src/targetB/compile_commands.json", "..", "../../outside.cpp");
    assertTrue(assertThrows(IllegalArgumentException.class,
        () -> ClangdGenerator.generate(List.of(b.toString()), root()))
        .getMessage().contains("outside configuration folder"));
    assertFalse(Files.exists(root().resolve("compdb/src/.clangd")));
  }

  @Test public void handlesEmptyDatabasesAndRejectsMissingInput() throws Exception {
    assertThrows(IllegalArgumentException.class, () -> ClangdGenerator.generate(List.of(), root()));
    assertThrows(IllegalArgumentException.class, () -> ClangdGenerator.generate(
        List.of(root().getRoot().toString()), root()));
    assertThrows(IOException.class, () -> ClangdGenerator.generate(
        List.of("missing/compile_commands.json"), root()));
    Path database = database("compdb/src/targetA/compile_commands.json", "..");
    Path config = root().resolve("compdb/src/.clangd");
    Files.writeString(config, "old mapping\n");
    ClangdGenerator.generate(List.of(database.toString()), root());
    assertEquals("# Generated by ccdb; manual edits will be overwritten.\n", Files.readString(config));
  }

  @Test public void mapsMainAndExternalRunfilesToExecrootPackages() {
    assertEquals(Path.of(""), BazelConfigGenerator.sourcePrefix("target/compile_commands.json"));
    assertEquals(Path.of("pkg"), BazelConfigGenerator.sourcePrefix("pkg/target/compile_commands.json"));
    assertEquals(Path.of("external/repo+"),
        BazelConfigGenerator.sourcePrefix("../repo+/target/compile_commands.json"));
    assertEquals(Path.of("external/repo+/pkg"),
        BazelConfigGenerator.sourcePrefix("../repo+/pkg/target/compile_commands.json"));
  }

  @Test public void bazelRunWritesBesideDatabasesUsingOriginalSourcePaths() throws Exception {
    Path execroot = root().resolve("original-execroot");
    Path database = database("bazel-out/config/bin/pkg/targetA/compile_commands.json",
        execroot.toString(), "pkg/foo.cpp");

    List<Path> outputs = BazelConfigGenerator.generate(Map.of(database, Path.of("pkg")));

    assertEquals(List.of(database.getParent().getParent().resolve(".clangd")), outputs);
    String yaml = Files.readString(outputs.getFirst());
    assertTrue(yaml.contains("    - \"foo\\\\.cpp\""));
    assertTrue(yaml.contains("CompilationDatabase: \"targetA\""));
    assertFalse(Files.exists(execroot.resolve("pkg/.clangd")));
  }

  @Test public void bazelRunValidatesBeforeWritingAndHandlesEmptyGraphs() throws Exception {
    Path a = database("bazel-out/config/bin/pkg/targetA/compile_commands.json",
        root().toString(), "pkg/foo.cpp");
    Path b = database("bazel-out/config/bin/other/targetB/compile_commands.json",
        root().toString(), "pkg/bar.cpp");
    Path config = a.getParent().getParent().resolve(".clangd");
    Files.writeString(config, "existing config\n");
    assertThrows(IllegalArgumentException.class, () -> BazelConfigGenerator.generate(
        Map.of(a, Path.of("pkg"), b, Path.of("other"))));
    assertEquals("existing config\n", Files.readString(config));
    assertEquals(List.of(), BazelConfigGenerator.generate(Map.of()));
    Files.writeString(a, "[]");
    BazelConfigGenerator.generate(Map.of(a, Path.of("pkg")));
    assertEquals("# Generated by ccdb; manual edits will be overwritten.\n", Files.readString(config));
  }

}
